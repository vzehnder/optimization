def catalog_projection_content_hash(rows) -> str:
    """Digest of the projected rows, used to compare a rebuild to the live table."""

    digest = hashlib.sha256()
    for row in rows:
        digest.update(
            "\x1f".join(str(row[column]) for column in CATALOG_ENTRY_COLUMNS).encode(
                "utf-8"
            )
        )
        digest.update(b"\n")
    return digest.hexdigest()


DEFAULT_CATALOG_ORDER = "-updated_at,display_name"

CATALOG_PAGE_DEFAULT_LIMIT = 50
CATALOG_PAGE_MAX_LIMIT = 200

CURSOR_LIFETIME_SECONDS = 15 * 60


class CatalogQueryError(RuntimeError):
    """A refusal from the catalog read model, carrying a stable code."""

    def __init__(self, code: str, **context):
        self.code = code
        self.context = context
        super().__init__(f"{code}: {context}" if context else code)


def parse_catalog_order(order: str | None) -> list[tuple[str, bool]]:
    """Translate an order expression into a total, deterministic key tuple."""

    expression = (order or DEFAULT_CATALOG_ORDER).strip()
    terms: list[tuple[str, bool]] = []
    seen: set[str] = set()
    for raw_term in expression.split(","):
        term = raw_term.strip()
        if not term:
            continue
        descending = term.startswith("-")
        name = term.lstrip("-+").strip()
        if name not in CATALOG_ORDER_COLUMNS:
            raise CatalogQueryError("TS_QUERY_ORDER_UNSUPPORTED", order=name)
        column = CATALOG_ORDER_COLUMNS[name]
        if column in seen:
            continue
        seen.add(column)
        terms.append((column, descending))
    terms.append(("signal_id", False))
    return terms


def normalize_catalog_order(order: str | None) -> str:
    """Canonical spelling of an order, so a cursor can be compared to it."""

    reverse = {column: name for name, column in CATALOG_ORDER_COLUMNS.items()}
    return ",".join(
        f"{'-' if descending else ''}{reverse[column]}"
        for column, descending in parse_catalog_order(order)
        if column in reverse
    )


def normalize_catalog_limit(limit: int | None) -> int:
    if limit is None:
        return CATALOG_PAGE_DEFAULT_LIMIT
    limit = int(limit)
    if limit < 1 or limit > CATALOG_PAGE_MAX_LIMIT:
        raise CatalogQueryError(
            "TS_QUERY_LIMIT_INVALID", limit=limit, maximum=CATALOG_PAGE_MAX_LIMIT
        )
    return limit


def catalog_page_sql(
    *,
    entries_table: str,
    order_terms: list[tuple[str, bool]],
    cursor_key: list | None,
    limit: int,
    filter_sql: str = "",
    filter_parameters: tuple = (),
) -> tuple[str, tuple]:
    """Keyset page over the projection, as a ladder of comparisons.

    ``OFFSET`` is never used, and the ladder never assumes both engines treat
    equality the same way; it only compares columns that are NOT NULL.
    """

    order_sql = ", ".join(
        f"{column} {'DESC' if descending else 'ASC'}"
        for column, descending in order_terms
    )
    parameters: list = list(filter_parameters)
    conditions: list[str] = []
    if filter_sql:
        conditions.append(f"({filter_sql})")
    if cursor_key is not None:
        if len(cursor_key) != len(order_terms):
            raise CatalogQueryError("TS_QUERY_CURSOR_MISMATCH", reason="key_arity")
        # The leading column also carries a non strict bound. It is redundant
        # with the ladder, but it is what lets the index start at the cursor
        # instead of at the top: without it the engine scans from the first row
        # and filters, and a keyset page degrades into an offset page.
        leading_column, leading_descending = order_terms[0]
        bound = f"{leading_column} {'<=' if leading_descending else '>='} ?"
        parameters.append(cursor_key[0])
        rungs = []
        for index, (column, descending) in enumerate(order_terms):
            comparison = "<" if descending else ">"
            equalities = " AND ".join(
                f"{order_terms[before][0]} = ?" for before in range(index)
            )
            rung = f"{column} {comparison} ?"
            if equalities:
                rung = f"{equalities} AND {rung}"
            rungs.append(f"({rung})")
            parameters.extend(cursor_key[:index])
            parameters.append(cursor_key[index])
        conditions.append(f"{bound} AND ({' OR '.join(rungs)})")
    where = f"WHERE {' AND '.join(conditions)}" if conditions else ""
    # One extra row answers ``has_more`` without a second count.
    parameters.append(limit + 1)
    return (
        f"SELECT entry.* FROM {entries_table} AS entry {where} "
        f"ORDER BY {order_sql} LIMIT ?",
        tuple(parameters),
    )



def object_context_page_sql(
    *,
    entries_table: str,
    associations_table: str,
    sets_table: str,
    signals_table: str,
    linkable_object_id: int,
    cursor_key: list | None,
    limit: int,
) -> tuple[str, tuple]:
    """Contextual list of one object as the ``UNION ALL`` of chapter 9.5.

    The catalog arm walks the object's active associations into the projection;
    the local arm walks the sets the object owns. Each arm keeps its own
    discriminator, they cannot overlap, and the keyset applies to the union - a
    local series is never found by looking its ID up in the global projection.

    Both arms carry the keyset and their own bound, so the union materializes at
    most two pages before its final ordering instead of every row an object can
    reach.
    """

    ordering = "ORDER BY updated_at DESC, signal_id ASC"

    def arm_keyset(updated_at_column: str, signal_id_column: str) -> str:
        if cursor_key is None:
            return ""
        # The non strict bound on the leading column is what lets each arm seek
        # instead of scanning from its first row.
        return (
            f"AND {updated_at_column} <= ? "
            f"AND (({updated_at_column} < ?) "
            f"OR ({updated_at_column} = ? AND {signal_id_column} > ?))"
        )

    keyset_parameters: list = (
        []
        if cursor_key is None
        else [cursor_key[0], cursor_key[0], cursor_key[0], cursor_key[1]]
    )

    catalog_arm = f"""
        SELECT * FROM (
            SELECT 'catalog' AS source, entry.signal_id AS signal_id,
                   entry.series_key AS series_key,
                   entry.display_name AS display_name,
                   entry.time_series_set_id AS time_series_set_id,
                   entry.semantic_type_key AS semantic_type_key,
                   entry.unit_key AS unit_key,
                   entry.updated_at AS updated_at,
                   association.binding_role_id AS binding_role_id
            FROM {associations_table} AS association
            JOIN {entries_table} AS entry
              ON entry.signal_id = association.signal_id
            WHERE association.linkable_object_id = ?
              AND association.status = 'active'
              {arm_keyset("entry.updated_at", "entry.signal_id")}
            {ordering}
            LIMIT ?
        ) AS catalog_arm
    """
    local_arm = f"""
        SELECT * FROM (
            SELECT 'object_specific' AS source,
                   signal.id AS signal_id,
                   signal.series_key AS series_key,
                   signal.display_name AS display_name,
                   the_set.id AS time_series_set_id,
                   -- Each arm is its own subquery, so an untyped NULL would
                   -- settle on a type before the union and stop matching.
                   CAST(NULL AS TEXT) AS semantic_type_key,
                   CAST(NULL AS TEXT) AS unit_key,
                   the_set.updated_at AS updated_at,
                   CAST(NULL AS BIGINT) AS binding_role_id
            FROM {sets_table} AS the_set
            JOIN {signals_table} AS signal
              ON signal.id = the_set.object_specific_signal_id
            WHERE the_set.owner_linkable_object_id = ?
              AND the_set.series_kind = 'object_specific'
              {arm_keyset("the_set.updated_at", "signal.id")}
            ORDER BY the_set.updated_at DESC, signal.id ASC
            LIMIT ?
        ) AS local_arm
    """
    parameters: list = [int(linkable_object_id), *keyset_parameters, limit + 1]
    parameters.extend([int(linkable_object_id), *keyset_parameters, limit + 1])
    parameters.append(limit + 1)
    sql = f"""
        SELECT * FROM (
            {catalog_arm}
            UNION ALL
            {local_arm}
        ) AS object_context
        {ordering}
        LIMIT ?
    """
    return sql, tuple(parameters)


def _b64(raw: bytes) -> str:
    return base64.urlsafe_b64encode(raw).decode("ascii").rstrip("=")


def _unb64(encoded: str) -> bytes:
    padding = "=" * (-len(encoded) % 4)
    return base64.urlsafe_b64decode(encoded + padding)


def encode_catalog_cursor(payload: dict, secret: bytes) -> str:
    """Opaque, signed cursor bound to section, order, limit and generation."""

    body = json.dumps(
        payload, sort_keys=True, separators=(",", ":"), ensure_ascii=False
    ).encode("utf-8")
    signature = hmac.new(secret, body, hashlib.sha256).digest()[:16]
    # Body and signature are encoded separately: a raw ``.`` inside the binary
    # signature would otherwise split the cursor in the wrong place.
    return f"{_b64(body)}.{_b64(signature)}"


def decode_catalog_cursor(
    cursor: str,
    secret: bytes,
    *,
    section: str,
    order: str,
    limit: int,
    generation: int,
    actor_class: str | None = None,
    filters_hash: str | None = None,
    now: float | None = None,
) -> list:
    """Return the keyset position, or refuse with a stable navigation code."""

    try:
        encoded_body, encoded_signature = cursor.split(".", 1)
        body = _unb64(encoded_body)
        signature = _unb64(encoded_signature)
        payload = json.loads(body.decode("utf-8"))
    except Exception as error:  # noqa: BLE001 - any malformed cursor is a mismatch
        raise CatalogQueryError(
            "TS_QUERY_CURSOR_MISMATCH", reason="unreadable"
        ) from error
    expected = hmac.new(secret, body, hashlib.sha256).digest()[:16]
    if not hmac.compare_digest(expected, signature):
        raise CatalogQueryError("TS_QUERY_CURSOR_MISMATCH", reason="signature")
    moment = time.time() if now is None else now
    if moment - float(payload.get("t", 0)) > CURSOR_LIFETIME_SECONDS:
        raise CatalogQueryError("TS_QUERY_CURSOR_EXPIRED")
    if (
        payload.get("s") != section
        or payload.get("o") != order
        or int(payload.get("l", -1)) != limit
        or (actor_class is not None and payload.get("a") != actor_class)
        or (filters_hash is not None and payload.get("f") != filters_hash)
    ):
        raise CatalogQueryError("TS_QUERY_CURSOR_MISMATCH", reason="query_changed")
    if int(payload.get("g", -1)) != generation:
        raise CatalogQueryError(
            "TS_QUERY_SNAPSHOT_CHANGED",
            cursor_generation=payload.get("g"),
            current_generation=generation,
        )
    return list(payload["k"])
