"""Transactional catalog projection for TS7-005 (chapters 9.3, 9.5, 9.7).

``time_series_catalog_entries`` is the only table a global catalog list reads.
It holds one row per signal of a ``catalog`` set, derived from the set's
``current_revision_id``, and it is maintained inside the same transaction that
seals a revision - never by a background job that can drift.

The table lands in the same physical space as the rest of the TS-7 expansion:
schema ``ts_next`` on PostgreSQL and a ``_next`` suffix on SQLite.
"""

