class CanonicalRevisionError(RuntimeError):
    """A refusal from the canonical content model, carrying a stable code."""

    def __init__(self, code: str, **context):
        message_key, field, message = CANONICAL_ERROR_CATALOG[code]
        self.code = code
        self.message_key = message_key
        self.message = message
        self.field = field
        self.context = context
        super().__init__(f"{code}: {context}" if context else code)

    def as_problem(self) -> dict[str, object]:
        return {
            "code": self.code,
            "message_key": self.message_key,
            "message": self.message,
            "field": self.field,
            "context": dict(self.context),
        }


