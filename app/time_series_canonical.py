def format_canonical_number(value: float) -> str:
    """Shortest round-trip decimal form, identical on both engines."""

    return repr(float(value))


class CanonicalContentHash:
    """Streaming canonical hash over ``ordinal, period_index`` (chapter 2.7).

    The digest covers only the content contract - never the set identity, its
    name or the revision number - so two identical contents hash equal on both
    engines and across different sets.
    """

    UNIT = "\x1f"

    def __init__(
        self,
        *,
        timezone: str,
        timestamp_convention: str,
        data_class_key: str,
    ):
        self._digest = hashlib.sha256()
        self._signal_count = 0
        self._period_count = 0
        self._value_count = 0
        self._write("canonical", str(CANONICAL_CONTENT_MODEL_VERSION))
        self._write("header", timezone, timestamp_convention, data_class_key)

    def _write(self, *fields: str) -> None:
        self._digest.update((self.UNIT.join(fields) + "\n").encode("utf-8"))

    def add_signal(
        self,
        *,
        ordinal: int,
        series_key: str,
        semantic_type_key: str,
        unit_key: str,
        data_class_key: str,
        signal_role: str,
        aggregation: str,
    ) -> None:
        self._write(
            "signal",
            str(ordinal),
            series_key,
            semantic_type_key,
            unit_key,
            data_class_key,
            signal_role,
            aggregation,
        )
        self._signal_count += 1

    def add_period(
        self,
        *,
        period_index: int,
        timestamp_start: str,
        timestamp_end: str,
        duration_hours: float,
    ) -> None:
        self._write(
            "period",
            str(period_index),
            timestamp_start,
            timestamp_end,
            format_canonical_number(duration_hours),
        )
        self._period_count += 1

    def add_value(self, *, ordinal: int, period_index: int, value: float) -> None:
        self._write(
            "value",
            str(ordinal),
            str(period_index),
            format_canonical_number(value),
        )
        self._value_count += 1

    @property
    def counts(self) -> tuple[int, int, int]:
        return self._signal_count, self._period_count, self._value_count

    def seal(self) -> str:
        self._write(
            "counts",
            str(self._signal_count),
            str(self._period_count),
            str(self._value_count),
        )
        return self._digest.hexdigest()


def normalize_canonical_signals(signals) -> list[dict]:
    """Validate the declared signal contract and freeze its ordinals."""

    normalized: list[dict] = []
    seen: set[str] = set()
    for ordinal, signal in enumerate(signals):
        series_key = str(signal.get("series_key") or "").strip()
        if not series_key:
            raise CanonicalRevisionError(
                "TS_INGEST_SIGNAL_SET_INCOMPLETE",
                ordinal=ordinal,
                reason="missing_series_key",
            )
        if series_key in seen:
            raise CanonicalRevisionError(
                "TS_INGEST_SIGNAL_SET_INCOMPLETE",
                series_key=series_key,
                reason="duplicated_series_key",
            )
        seen.add(series_key)
        signal_role = str(signal.get("signal_role") or "input")
        if signal_role not in ("input", "output", "metadata"):
            raise CanonicalRevisionError(
                "TS_INGEST_SIGNAL_SET_INCOMPLETE",
                series_key=series_key,
                signal_role=signal_role,
                reason="unknown_signal_role",
            )
        normalized.append(
            {
                "ordinal": ordinal,
                "series_key": series_key,
                "display_name": str(signal.get("display_name") or series_key),
                "description": str(signal.get("description") or ""),
                "semantic_type_key": str(signal.get("semantic_type_key") or ""),
                "unit_key": str(signal.get("unit_key") or ""),
                "data_class_key": signal.get("data_class_key"),
                "signal_role": signal_role,
                "aggregation": signal.get("aggregation"),
                "metadata": signal.get("metadata") or {},
            }
        )
    if not normalized:
        raise CanonicalRevisionError(
            "TS_INGEST_SIGNAL_SET_INCOMPLETE", reason="no_signals"
        )
    return normalized


def normalize_canonical_periods(periods) -> list[dict]:
    """Validate ordered, non-overlapping coverage before anything is written."""

    normalized: list[dict] = []
    for position, period in enumerate(periods):
        declared_index = period.get("period_index")
        period_index = position if declared_index is None else int(declared_index)
        timestamp_start = str(period.get("timestamp_start") or "")
        timestamp_end = str(period.get("timestamp_end") or "")
        if not timestamp_start or not timestamp_end:
            raise CanonicalRevisionError(
                "TS_INGEST_PERIOD_CONFLICT",
                period_index=period_index,
                reason="missing_timestamp",
            )
        duration_hours = period.get("duration_hours")
        if duration_hours is None:
            raise CanonicalRevisionError(
                "TS_INGEST_DURATION_INVALID",
                period_index=period_index,
                reason="missing_duration",
            )
        duration_hours = float(duration_hours)
        if not duration_hours > 0:
            raise CanonicalRevisionError(
                "TS_INGEST_DURATION_INVALID",
                period_index=period_index,
                duration_hours=duration_hours,
            )
        if timestamp_end <= timestamp_start:
            raise CanonicalRevisionError(
                "TS_INGEST_DURATION_INVALID",
                period_index=period_index,
                reason="end_before_start",
            )
        normalized.append(
            {
                "period_index": period_index,
                "timestamp_start": timestamp_start,
                "timestamp_end": timestamp_end,
                "duration_hours": duration_hours,
            }
        )
    if not normalized:
        raise CanonicalRevisionError(
            "TS_INGEST_TEMPORAL_CONTRACT_INVALID", reason="no_periods"
        )
    for position, period in enumerate(normalized):
        if period["period_index"] != position:
            raise CanonicalRevisionError(
                "TS_INGEST_PERIOD_CONFLICT",
                period_index=period["period_index"],
                expected_period_index=position,
                reason="coverage_not_ordered",
            )
        if position == 0:
            continue
        previous = normalized[position - 1]
        if period["timestamp_start"] < previous["timestamp_end"]:
            raise CanonicalRevisionError(
                "TS_INGEST_PERIOD_CONFLICT",
                period_index=period["period_index"],
                reason="periods_overlap",
            )
        if period["timestamp_start"] <= previous["timestamp_start"]:
            raise CanonicalRevisionError(
                "TS_INGEST_PERIOD_CONFLICT",
                period_index=period["period_index"],
                reason="coverage_not_ordered",
            )
    return normalized


def canonical_value_records(values):
    """Yield ``(series_key, period_index, value, quality_flag, row_number)``.

    A mapping is read as one dense column per series; any other iterable is
    consumed lazily, so a publication whose source dies halfway really dies
    halfway and must roll back (AC-ESP-10).
    """

    if hasattr(values, "items"):
        for series_key, series_values in values.items():
            for period_index, value in enumerate(series_values):
                yield str(series_key), period_index, value, None, None
        return
    for record in values:
        yield (
            str(record.get("series_key") or ""),
            record.get("period_index"),
            record.get("value"),
            record.get("quality_flag"),
            record.get("source_row_number"),
        )
