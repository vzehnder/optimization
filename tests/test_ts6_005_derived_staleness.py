class VariantBoundToDerivedSetTests(unittest.TestCase):
    """A variant bound to a derived set composes with the TS-3 fail-closed gates."""

    def setUp(self):
        from app.variant_staleness import VariantStaleError

        self.VariantStaleError = VariantStaleError
        self.store = AnalystStore("sqlite:///:memory:")
        self.addCleanup(self.store.close)
        self.project = self.store.create_project(name="TS6-005 variant project")
        self.scenario = self.store.create_scenario(
            project_id=self.project["id"], name="TS6-005 variant scenario"
        )
        self.store.create_or_replace_scenario_draft(
            scenario_id=self.scenario["id"], document=grid_battery_draft_document()
        )
        self.case = self.store.get_or_create_case_for_scenario(self.scenario["id"])
        self.variant = self.store.get_or_create_default_input_variant(self.case["id"])

        prepared_price = prepare_time_series_catalog_import(
            rows=price_rows(datetime(2026, 1, 1), 3),
            request=price_import_request(),
        )
        self.price_set = self.store.import_time_series_catalog_set(
            scenario_id=self.scenario["id"],
            source={
                "id": "csv_source_price",
                "original_filename": "price.csv",
                "media_type": "text/csv",
                "checksum": "sha256:price",
            },
            prepared_import=prepared_price,
        )
        self.derived_set = self.store.apply_time_series_transformation(
            project_id=self.project["id"],
            time_series_set_id=self.price_set["id"],
            transformation_type="scale_signal",
            raw_parameters={
                "signal_key": "import_price_usd_per_mwh",
                "scale_factor": 2.0,
            },
        )
        self.store.upsert_case_time_series_binding(
            case_input_variant_id=self.variant["id"],
            signal_key="import_price_usd_per_mwh",
            time_series_set_id=self.derived_set["id"],
        )

    def _edit_price_source(self):
        self.store.edit_time_series_set_values(
            project_id=self.project["id"],
            time_series_set_id=self.price_set["id"],
            edits=[
                CatalogValueEdit(
                    period_index=0,
                    signal_key="import_price_usd_per_mwh",
                    value_text="999.0",
                )
            ],
        )

    def _materialize(self):
        return self.store.materialize_system_case_for_variant(
            scenario_id=self.scenario["id"],
            case_input_variant_id=self.variant["id"],
            range_start=self.derived_set["horizon"]["start"],
            range_end=self.derived_set["horizon"]["end"],
        )

    def _validate(self):
        return self.store.validate_case_input_variant(
            scenario_id=self.scenario["id"],
            case_input_variant_id=self.variant["id"],
            range_start=self.derived_set["horizon"]["start"],
            range_end=self.derived_set["horizon"]["end"],
        )

    def _staleness(self):
        return self.store.evaluate_case_input_variant_staleness(
            scenario_id=self.scenario["id"], case_input_variant_id=self.variant["id"]
        )

    def test_validated_variant_goes_stale_when_the_derived_sets_source_moves(self):
        self._materialize()
        self.assertFalse(self._staleness()["stale"])

        self._edit_price_source()

        staleness = self._staleness()
        self.assertTrue(staleness["stale"])
        self.assertIn(
            "time_series_set_derived_staleness",
            [reason["dependency_type"] for reason in staleness["reasons"]],
        )
        with self.assertRaises(self.VariantStaleError):
            self._materialize()

    def test_unvalidated_variant_is_also_blocked_while_the_derived_set_is_stale(self):
        self._edit_price_source()

        with self.assertRaises(self.VariantStaleError):
            self._materialize()

    def test_revalidation_stays_blocked_until_the_derived_set_is_regenerated(self):
        self._materialize()
        self._edit_price_source()

        with self.assertRaises(self.VariantStaleError):
            self._validate()

    def test_regenerating_and_revalidating_unblocks_the_variant(self):
        self._materialize()
        self._edit_price_source()

        self.store.regenerate_derived_time_series_set(
            project_id=self.project["id"],
            time_series_set_id=self.derived_set["id"],
        )
        staleness = self._staleness()
        self.assertTrue(staleness["stale"])
        self.assertEqual(
            [reason["dependency_type"] for reason in staleness["reasons"]],
            ["time_series_set"],
        )

        self._validate()
        self.assertFalse(self._staleness()["stale"])
        materialized = self._materialize()
        self.assertTrue(materialized["system_case"]["time_series"])


