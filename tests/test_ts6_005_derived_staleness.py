class DerivedSetStalenessTests(DerivedScaleFixtureMixin, unittest.TestCase):
    def test_fresh_derived_set_is_not_stale(self):
        staleness = self.store.evaluate_time_series_set_staleness(
            self.project["id"], self.derived_set["id"]
        )

        self.assertTrue(staleness["validated"])
        self.assertFalse(staleness["stale"])
        self.assertEqual(staleness["reasons"], [])

    def test_new_source_revision_marks_the_derived_set_stale(self):
        self._edit_source()

        staleness = self.store.evaluate_time_series_set_staleness(
            self.project["id"], self.derived_set["id"]
        )

        self.assertTrue(staleness["stale"])
        self.assertEqual(
            [reason["dependency_type"] for reason in staleness["reasons"]],
            ["time_series_set"],
        )
        self.assertEqual(
            staleness["reasons"][0]["dependency_id"], str(self.source_set["id"])
        )

    def test_non_derived_sets_are_never_stale(self):
        self._edit_source()

        staleness = self.store.evaluate_time_series_set_staleness(
            self.project["id"], self.source_set["id"]
        )

        self.assertFalse(staleness["validated"])
        self.assertFalse(staleness["stale"])

    def test_catalog_list_flags_stale_derived_sets(self):
        self._edit_source()

        sets_by_id = {
            entry["id"]: entry
            for entry in self.store.list_time_series_sets(self.project["id"])
        }

        self.assertTrue(sets_by_id[self.derived_set["id"]]["stale"])
        self.assertFalse(sets_by_id[self.source_set["id"]]["stale"])

    def test_catalog_list_does_not_flag_fresh_derived_sets(self):
        sets_by_id = {
            entry["id"]: entry
            for entry in self.store.list_time_series_sets(self.project["id"])
        }

        self.assertFalse(sets_by_id[self.derived_set["id"]]["stale"])

    def test_bumping_the_implementation_version_marks_derived_outputs_stale(self):
        import dataclasses
        from unittest import mock

        from app import transformations

        bumped = dataclasses.replace(
            transformations.TRANSFORMATION_REGISTRY["scale_signal"],
            implementation_version=2,
        )
        patched_registry = {
            **transformations.TRANSFORMATION_REGISTRY,
            "scale_signal": bumped,
        }
        with mock.patch.object(
            transformations, "TRANSFORMATION_REGISTRY", patched_registry
        ):
            staleness = self.store.evaluate_time_series_set_staleness(
                self.project["id"], self.derived_set["id"]
            )

        self.assertTrue(staleness["stale"])
        self.assertEqual(
            [reason["dependency_type"] for reason in staleness["reasons"]],
            ["transformation_implementation"],
        )


class RegenerateDerivedSetTests(DerivedScaleFixtureMixin, unittest.TestCase):
    def test_regenerating_a_stale_set_re_executes_the_recipe_on_current_inputs(self):
        self._edit_source(value_text="200.0")

        regenerated = self.store.regenerate_derived_time_series_set(
            project_id=self.project["id"],
            time_series_set_id=self.derived_set["id"],
            created_by="analyst@example.com",
        )

        self.assertEqual(regenerated["id"], self.derived_set["id"])
        self.assertEqual(regenerated["revision_number"], 2)
        self.assertNotEqual(regenerated["content_hash"], self.derived_set["content_hash"])
        values_by_key = {
            (value["period_index"], value["signal_key"]): value["value_numeric"]
            for value in regenerated["values"]
        }
        self.assertAlmostEqual(values_by_key[(0, "load_demand_mw")], 400.0)
        self.assertAlmostEqual(values_by_key[(0, "import_price_usd_per_mwh")], 50.0)

    def test_regeneration_updates_lineage_and_clears_staleness(self):
        self._edit_source(value_text="200.0")
        current_source = self.store.get_time_series_set(
            self.project["id"], self.source_set["id"]
        )

        regenerated = self.store.regenerate_derived_time_series_set(
            project_id=self.project["id"],
            time_series_set_id=self.derived_set["id"],
        )

        transformation = regenerated["revision_metadata"]["transformation"]
        self.assertEqual(transformation["type"], "scale_signal")
        self.assertEqual(
            transformation["parameters"],
            {"signal_key": "load_demand_mw", "scale_factor": 2.0},
        )
        lineage_input = transformation["inputs"][0]
        self.assertEqual(lineage_input["time_series_set_id"], self.source_set["id"])
        self.assertEqual(lineage_input["revision_number"], current_source["revision_number"])
        self.assertEqual(lineage_input["content_hash"], current_source["content_hash"])
        staleness = self.store.evaluate_time_series_set_staleness(
            self.project["id"], self.derived_set["id"]
        )
        self.assertFalse(staleness["stale"])

    def test_regenerating_a_fresh_set_converges_without_a_new_revision(self):
        regenerated = self.store.regenerate_derived_time_series_set(
            project_id=self.project["id"],
            time_series_set_id=self.derived_set["id"],
        )

        self.assertEqual(regenerated["revision_number"], 1)
        self.assertEqual(regenerated["content_hash"], self.derived_set["content_hash"])
        revisions = self.store.list_time_series_set_revisions(
            self.project["id"], self.derived_set["id"]
        )
        self.assertEqual(len(revisions), 1)

    def test_regeneration_preserves_the_previous_revision_untouched(self):
        self._edit_source(value_text="200.0")

        self.store.regenerate_derived_time_series_set(
            project_id=self.project["id"],
            time_series_set_id=self.derived_set["id"],
        )

        revisions = self.store.list_time_series_set_revisions(
            self.project["id"], self.derived_set["id"]
        )
        by_number = {revision["revision_number"]: revision for revision in revisions}
        self.assertEqual(sorted(by_number), [1, 2])
        self.assertEqual(
            by_number[1]["content_hash"], self.derived_set["content_hash"]
        )
        self.assertEqual(by_number[2]["superseded_revision_number"], 1)

    def test_regenerating_a_non_derived_set_is_rejected(self):
        from app.transformations import TransformationError

        with self.assertRaises(TransformationError):
            self.store.regenerate_derived_time_series_set(
                project_id=self.project["id"],
                time_series_set_id=self.source_set["id"],
            )


