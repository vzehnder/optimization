"""BESS-TS6-005: derived-set staleness and regeneration.

Proves the derived-data lifecycle: a new revision of a source set marks every
derived set produced from it stale (Layer 1, reusing the generic
`validation_dependencies` + `evaluate_variant_staleness` mechanism with
`owner_type = 'time_series_set'`), a stale derived set can be regenerated by
re-executing its stored recipe against current input revisions (a new revision
of the same set, never a new set), history stays immutable, and a variant
bound to a stale derived set is blocked through the existing TS-3 fail-closed
gates.
"""

import unittest
from datetime import datetime, timedelta

from app.persistence import AnalystStore
from app.time_series_catalog import (
    CatalogImportRequest,
    CatalogSignalMappingRequest,
    CatalogValueEdit,
    prepare_time_series_catalog_import,
)


def demand_price_import_request(*, version_label="v1"):
    return CatalogImportRequest(
        set_name="Demand and price base",
        version_label=version_label,
        data_kind="real",
        timezone="America/Santiago",
        timestamp_column="period_start",
        duration_hours_column="hours",
        signal_mappings=[
            CatalogSignalMappingRequest(source_column="demand", signal_key="load_demand_mw"),
            CatalogSignalMappingRequest(
                source_column="price", signal_key="import_price_usd_per_mwh"
            ),
        ],
    )


def demand_price_rows(start, count):
    rows = []
    for hour in range(count):
        instant = start + timedelta(hours=hour)
        rows.append(
            {
                "period_start": instant.isoformat(),
                "hours": "1.0",
                "demand": str(100.0 + hour),
                "price": str(50.0 + hour),
            }
        )
    return rows


